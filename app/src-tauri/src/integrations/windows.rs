//! Windows Explorer verbs under `HKCU\Software\Classes` (per user, no admin rights).
//!
//! The same entries are written by the NSIS installer hook (`windows/hooks.nsh`, generated
//! from [`nsis_hooks`] and checked by a test) so a fresh install has the menu right away.

#![cfg_attr(not(windows), allow(dead_code))]

use std::collections::BTreeMap;
use std::io;
use std::path::Path;

use super::{IntegrationStatus, EXTENSIONS, MENU_LABEL};

/// Name of our verb key under every `shell` key.
pub const VERB: &str = "CompressImages";
const CLASSES: &str = r"Software\Classes";

/// One registry key with its string values (`""` = the key's default value).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct RegEntry {
    pub key: String,
    pub values: Vec<(String, String)>,
}

/// Verb keys we own; removing these removes everything we wrote.
pub fn verb_keys() -> Vec<String> {
    let mut keys: Vec<String> = EXTENSIONS
        .iter()
        .map(|ext| format!(r"{CLASSES}\SystemFileAssociations\.{ext}\shell\{VERB}"))
        .collect();
    keys.push(format!(r"{CLASSES}\Directory\shell\{VERB}"));
    keys.push(format!(r"{CLASSES}\Directory\Background\shell\{VERB}"));
    keys
}

/// Everything to write, with `exe` as the program path (quoted inside the command).
pub fn entries(exe: &str) -> Vec<RegEntry> {
    let icon = format!("\"{exe}\",0");
    let mut out = Vec::new();
    for key in verb_keys() {
        let background = key.contains(r"\Background\");
        let mut values = vec![
            ("MUIVerb".to_string(), MENU_LABEL.to_string()),
            ("Icon".to_string(), icon.clone()),
        ];
        if key.contains("SystemFileAssociations") {
            // Without this Explorer hides the verb when more than 15 files are selected.
            values.push(("MultiSelectModel".to_string(), "Player".to_string()));
        }
        out.push(RegEntry {
            key: key.clone(),
            values,
        });
        // %1 = the clicked item; %V = the folder whose background was clicked.
        let arg = if background { "%V" } else { "%1" };
        out.push(RegEntry {
            key: format!(r"{key}\command"),
            values: vec![(String::new(), format!("\"{exe}\" --compress \"{arg}\""))],
        });
    }
    out
}

/// Minimal registry interface so install/uninstall logic is testable off Windows.
pub trait Registry {
    fn set(&mut self, key: &str, name: &str, value: &str) -> io::Result<()>;
    fn get(&self, key: &str, name: &str) -> Option<String>;
    /// Deletes `key` and all subkeys; succeeds if it doesn't exist.
    fn delete_tree(&mut self, key: &str) -> io::Result<()>;
}

pub fn install(reg: &mut dyn Registry, exe: &Path) -> io::Result<()> {
    let exe = exe.to_string_lossy();
    for e in entries(&exe) {
        for (name, value) in &e.values {
            reg.set(&e.key, name, value)?;
        }
    }
    Ok(())
}

pub fn uninstall(reg: &mut dyn Registry) -> io::Result<()> {
    for key in verb_keys() {
        reg.delete_tree(&key)?;
    }
    Ok(())
}

pub fn status(reg: &dyn Registry, exe: &Path) -> IntegrationStatus {
    let probe = format!(r"{CLASSES}\Directory\shell\{VERB}\command");
    let command = reg.get(&probe, "");
    let exe = exe.to_string_lossy();
    IntegrationStatus {
        supported: true,
        installed: command.is_some(),
        outdated: command.is_some_and(|c| !c.contains(exe.as_ref())),
        targets: vec!["Explorer".into()],
    }
}

/// NSIS macros for the installer: register on install, remove on uninstall.
pub fn nsis_hooks() -> String {
    // NSIS: `$\"` is a literal double quote; `$INSTDIR` is the install folder.
    let exe = r"$INSTDIR\compress-images-app.exe";
    let nsis = |s: &str| s.replace('"', "$\\\"");
    let mut out = String::from(
        "; Generated by `cargo test -p compress-images-app -- --ignored regenerate_nsis_hooks`.\n\
         ; Do not edit by hand: the test `nsis_hooks_are_up_to_date` checks this file.\n\n",
    );
    out.push_str("!macro NSIS_HOOK_POSTINSTALL\n");
    for e in entries(exe) {
        for (name, value) in &e.values {
            out.push_str(&format!(
                "  WriteRegStr HKCU \"{}\" \"{}\" \"{}\"\n",
                e.key,
                name,
                nsis(value)
            ));
        }
    }
    out.push_str("!macroend\n\n!macro NSIS_HOOK_POSTUNINSTALL\n");
    for key in verb_keys() {
        out.push_str(&format!("  DeleteRegKey HKCU \"{key}\"\n"));
    }
    out.push_str("!macroend\n");
    out
}

/// In-memory registry for tests.
#[derive(Default, Debug)]
pub struct FakeRegistry {
    pub keys: BTreeMap<String, BTreeMap<String, String>>,
}

impl Registry for FakeRegistry {
    fn set(&mut self, key: &str, name: &str, value: &str) -> io::Result<()> {
        self.keys
            .entry(key.to_lowercase())
            .or_default()
            .insert(name.to_string(), value.to_string());
        Ok(())
    }
    fn get(&self, key: &str, name: &str) -> Option<String> {
        self.keys.get(&key.to_lowercase())?.get(name).cloned()
    }
    fn delete_tree(&mut self, key: &str) -> io::Result<()> {
        let prefix = format!("{}\\", key.to_lowercase());
        let k = key.to_lowercase();
        self.keys
            .retain(|existing, _| existing != &k && !existing.starts_with(&prefix));
        Ok(())
    }
}

/// The real `HKEY_CURRENT_USER` registry.
#[cfg(windows)]
pub struct SystemRegistry;

#[cfg(windows)]
impl Registry for SystemRegistry {
    fn set(&mut self, key: &str, name: &str, value: &str) -> io::Result<()> {
        use winreg::enums::HKEY_CURRENT_USER;
        let (k, _) = winreg::RegKey::predef(HKEY_CURRENT_USER).create_subkey(key)?;
        k.set_value(name, &value)
    }
    fn get(&self, key: &str, name: &str) -> Option<String> {
        use winreg::enums::HKEY_CURRENT_USER;
        winreg::RegKey::predef(HKEY_CURRENT_USER)
            .open_subkey(key)
            .ok()?
            .get_value(name)
            .ok()
    }
    fn delete_tree(&mut self, key: &str) -> io::Result<()> {
        use winreg::enums::HKEY_CURRENT_USER;
        match winreg::RegKey::predef(HKEY_CURRENT_USER).delete_subkey_all(key) {
            Err(e) if e.kind() == io::ErrorKind::NotFound => Ok(()),
            other => other,
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::path::PathBuf;

    const EXE: &str = r"C:\Users\me\AppData\Local\Compress Images\compress-images-app.exe";

    #[test]
    fn entries_cover_every_extension_folders_and_background() {
        let e = entries(EXE);
        for ext in EXTENSIONS {
            let key =
                format!(r"Software\Classes\SystemFileAssociations\.{ext}\shell\CompressImages");
            assert!(e.iter().any(|x| x.key == key), "{ext}");
        }
        let cmd = |key: &str| {
            e.iter()
                .find(|x| x.key == key)
                .map(|x| x.values[0].1.clone())
                .unwrap()
        };
        assert_eq!(
            cmd(r"Software\Classes\Directory\shell\CompressImages\command"),
            format!("\"{EXE}\" --compress \"%1\"")
        );
        assert_eq!(
            cmd(r"Software\Classes\Directory\Background\shell\CompressImages\command"),
            format!("\"{EXE}\" --compress \"%V\"")
        );
        let jpg = e
            .iter()
            .find(|x| x.key.ends_with(r".jpg\shell\CompressImages"))
            .unwrap();
        assert!(jpg
            .values
            .contains(&("MultiSelectModel".into(), "Player".into())));
    }

    #[test]
    fn install_status_uninstall_round_trip() {
        let mut reg = FakeRegistry::default();
        // Unrelated key that must survive uninstall.
        reg.set(r"Software\Classes\Directory\shell\Other", "", "x")
            .unwrap();
        let exe = PathBuf::from(EXE);

        assert!(!status(&reg, &exe).installed);
        install(&mut reg, &exe).unwrap();
        let s = status(&reg, &exe);
        assert!(s.installed && !s.outdated);

        let moved = PathBuf::from(r"D:\Apps\compress-images-app.exe");
        assert!(status(&reg, &moved).outdated);

        uninstall(&mut reg).unwrap();
        assert!(!status(&reg, &exe).installed);
        assert_eq!(reg.keys.len(), 1, "only the unrelated key remains: {reg:?}");
    }

    #[test]
    fn nsis_hooks_are_up_to_date() {
        let path = Path::new(env!("CARGO_MANIFEST_DIR")).join("windows/hooks.nsh");
        let on_disk = std::fs::read_to_string(&path).unwrap_or_default();
        assert!(
            on_disk.replace("\r\n", "\n") == nsis_hooks(),
            "{} is stale; run: cargo test -p compress-images-app -- --ignored regenerate_nsis_hooks",
            path.display()
        );
    }

    #[test]
    #[ignore = "writes windows/hooks.nsh"]
    fn regenerate_nsis_hooks() {
        let path = Path::new(env!("CARGO_MANIFEST_DIR")).join("windows/hooks.nsh");
        std::fs::create_dir_all(path.parent().unwrap()).unwrap();
        std::fs::write(path, nsis_hooks()).unwrap();
    }

    #[test]
    fn nsis_quotes_are_escaped() {
        let h = nsis_hooks();
        assert!(h.contains(
            r#"WriteRegStr HKCU "Software\Classes\Directory\shell\CompressImages\command" "" "$\"$INSTDIR\compress-images-app.exe$\" --compress $\"%1$\"""#
        ));
        assert!(h.contains(r#"DeleteRegKey HKCU "Software\Classes\SystemFileAssociations\.heic\shell\CompressImages""#));
    }
}
